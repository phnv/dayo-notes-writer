#!/usr/bin/env python3
"""Generate per-bundle launcher scripts in ``user_scripts/`` from ``config/config.yaml``.

For every bundle a bash script (``<bundle>.sh``) and, optionally, a Windows wrapper
(``<bundle>.cmd`` that calls ``wsl.exe``) are written. Each launcher runs
``note-writer`` with the bundle pre-selected.

Usage (from the project root, inside WSL):

    uv run python scripts/build_user_scripts.py --list
    uv run python scripts/build_user_scripts.py --bundle meeting_notes
    uv run python scripts/build_user_scripts.py --all [--provider gemini] [--clean]
    uv run python scripts/build_user_scripts.py --clean

Bundle resolution rules:
  * Operation: ``update`` when the bundle's prompt alias is ``update``, otherwise
    ``write``. A bundle may override this with an optional ``command: write|update`` key.
  * Provider: ``--provider`` flag, then the bundle's optional ``provider:`` key, otherwise
    nothing is baked in and ``DAYO_LLM_PROVIDER`` from ``.env`` decides at runtime.
  * A missing storage/template alias falls back to the one of the ``defaults.bundle``
    bundle (with a warning). If no valid fallback exists, or the prompt alias is missing,
    the bundle is skipped.
"""
from __future__ import annotations

import argparse
import os
import re
import shlex
import stat
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CONFIG = PROJECT_ROOT / "config" / "config.yaml"
OUTPUT_DIR = PROJECT_ROOT / "user_scripts"
GENERATED_MARKER = "GENERATED by scripts/build_user_scripts.py"
SAFE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
PROVIDERS = ("openai", "gemini")
COMMANDS = ("write", "update")


@dataclass
class Plan:
    """Resolved launcher definition for one bundle."""

    name: str
    command: str
    provider: str | None
    extra_flags: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    skip_reason: str | None = None


# ---------------------------------------------------------------------------
# Planning
# ---------------------------------------------------------------------------

def load_config(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
    if not isinstance(data, dict):
        raise SystemExit(f"error: {path} is not a YAML mapping")
    return data


def _default_fallbacks(cfg: dict) -> tuple[str | None, str | None]:
    """Return (template, storage) of the default bundle, if each one is valid."""
    bundles = cfg.get("bundles") or {}
    default_name = (cfg.get("defaults") or {}).get("bundle")
    default = bundles.get(default_name) if default_name else None
    if not isinstance(default, dict):
        return None, None
    template = default.get("template")
    storage = default.get("storage")
    if template not in (cfg.get("templates") or {}):
        template = None
    if storage not in (cfg.get("storage") or {}):
        storage = None
    return template, storage


def plan_bundle(name: str, cfg: dict, cli_provider: str | None) -> Plan:
    bundle = (cfg.get("bundles") or {}).get(name) or {}
    templates = cfg.get("templates") or {}
    prompts = cfg.get("prompts") or {}
    storages = cfg.get("storage") or {}

    prompt = bundle.get("prompt")
    command = bundle.get("command") or ("update" if prompt == "update" else "write")
    provider = cli_provider or bundle.get("provider")
    plan = Plan(name=name, command=command, provider=provider)

    if not SAFE_NAME.match(name):
        plan.skip_reason = "bundle name has characters unsafe for a file name"
        return plan
    if command not in COMMANDS:
        plan.skip_reason = f"invalid command '{command}' (expected one of {COMMANDS})"
        return plan
    if provider and provider not in PROVIDERS:
        plan.skip_reason = f"invalid provider '{provider}' (expected one of {PROVIDERS})"
        return plan
    if prompt and prompt not in prompts:
        plan.skip_reason = f"prompt '{prompt}' is not defined under 'prompts'"
        return plan

    fallback_template, fallback_storage = _default_fallbacks(cfg)

    template = bundle.get("template")
    if command == "write" and template not in templates:
        if fallback_template:
            plan.extra_flags += ["--template", fallback_template]
            plan.notes.append(
                f"template '{template}' is not defined; fell back to '{fallback_template}'"
            )
        else:
            plan.skip_reason = f"template '{template}' is not defined and no default fallback exists"
            return plan

    storage = bundle.get("storage")
    if storage not in storages:
        if fallback_storage:
            plan.extra_flags += ["--storage", fallback_storage]
            plan.notes.append(
                f"storage '{storage}' is not defined; fell back to '{fallback_storage}'"
            )
        else:
            plan.skip_reason = f"storage '{storage}' is not defined and no default fallback exists"
            return plan

    filename = bundle.get("filename")
    # The update flow does not resolve the bundle filename itself, so pass it explicitly.
    if command == "update" and filename and "{" not in str(filename):
        plan.extra_flags += ["--file", str(filename)]

    return plan


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def render_sh(plan: Plan) -> str:
    cli = ["note-writer"]
    if plan.provider:
        cli += ["--provider", plan.provider]
    cli += [plan.command, "--bundle", plan.name, *plan.extra_flags]
    base_cmd = " ".join(shlex.quote(part) for part in cli)

    notes = "".join(f"# NOTE: {note}\n" for note in plan.notes)
    return f"""#!/usr/bin/env bash
# {GENERATED_MARKER} -- do not edit; re-run the master script instead.
# Bundle: {plan.name} | Operation: {plan.command} | Provider: {plan.provider or "from .env (DAYO_LLM_PROVIDER)"}
{notes}#
# Usage: {plan.name}.sh [--text "..." | --clipboard] [extra note-writer options]
#   Input defaults to the clipboard when run from a terminal without --text/--clipboard.
#   Piped stdin is used as input when provided. Extra options override the baked-in ones.
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${{BASH_SOURCE[0]}}")/.." && pwd)"
cd "$PROJECT_ROOT"

if command -v uv >/dev/null 2>&1; then
  UV="$(command -v uv)"
else
  UV="$HOME/.local/bin/uv"
fi

args=("$@")
has_input=0
for arg in "$@"; do
  case "$arg" in
    --text|--text=*|--clipboard) has_input=1 ;;
  esac
done
if [ "$has_input" -eq 0 ] && [ -t 0 ]; then
  args+=(--clipboard)
fi

EXIT_CODE=0
"$UV" run {base_cmd} "${{args[@]}}" || EXIT_CODE=$?

echo ""
if [ -t 0 ]; then
  read -rp "Press Enter to exit..." || true
elif [ -r /dev/tty ]; then
  read -rp "Press Enter to exit..." < /dev/tty || true
fi

exit "$EXIT_CODE"
"""


def render_cmd(plan: Plan, linux_script: str, distro: str | None) -> str:
    distro_flag = f"-d {distro} " if distro else ""
    return (
        "@echo off\n"
        f"REM {GENERATED_MARKER} -- do not edit; re-run the master script instead.\n"
        f"wsl.exe {distro_flag}-- bash \"{linux_script}\" %*\n"
    )


# ---------------------------------------------------------------------------
# I/O
# ---------------------------------------------------------------------------

def write_file(path: Path, content: str, executable: bool = False) -> None:
    # Always LF line endings (project rule), even for .cmd wrappers.
    path.write_text(content, encoding="utf-8", newline="\n")
    if executable:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def clean_stale(bundle_names: set[str], out_dir: Path) -> list[Path]:
    removed: list[Path] = []
    if not out_dir.is_dir():
        return removed
    for path in sorted(out_dir.iterdir()):
        if path.suffix in {".sh", ".cmd"} and path.stem not in bundle_names and is_generated(path):
            path.unlink()
            removed.append(path)
    return removed


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate per-bundle launcher scripts in user_scripts/ from config.yaml."
    )
    target = parser.add_mutually_exclusive_group()
    target.add_argument("--bundle", metavar="NAME", help="Generate scripts for a single bundle.")
    target.add_argument("--all", action="store_true", help="Generate scripts for every bundle.")
    target.add_argument("--list", action="store_true", help="List bundles and their planned operation.")
    parser.add_argument("--clean", action="store_true",
                        help="Remove generated scripts of bundles no longer in the config.")
    parser.add_argument("--provider", choices=PROVIDERS,
                        help="Bake this LLM provider into the scripts (default: use DAYO_LLM_PROVIDER from .env).")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG, help="Path to config.yaml.")
    parser.add_argument("--out-dir", type=Path, default=OUTPUT_DIR, help="Output directory.")
    parser.add_argument("--no-cmd", action="store_true", help="Skip the Windows .cmd wrappers.")
    parser.add_argument("--distro", default=os.environ.get("WSL_DISTRO_NAME"),
                        help="WSL distro used by .cmd wrappers (default: $WSL_DISTRO_NAME).")
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    if not (args.bundle or args.all or args.list or args.clean):
        parser.error("choose one of --bundle NAME, --all, --list or --clean")

    cfg = load_config(args.config)
    bundles = cfg.get("bundles") or {}

    if args.list:
        for name in bundles:
            plan = plan_bundle(name, cfg, args.provider)
            status = f"SKIP ({plan.skip_reason})" if plan.skip_reason else plan.command
            suffix = f" [{'; '.join(plan.notes)}]" if plan.notes else ""
            print(f"{name}: {status}{suffix}")
        return 0

    exit_code = 0

    if args.bundle or args.all:
        if args.bundle and args.bundle not in bundles:
            print(f"error: bundle '{args.bundle}' not found in {args.config}", file=sys.stderr)
            return 2
        names = [args.bundle] if args.bundle else list(bundles)
        args.out_dir.mkdir(parents=True, exist_ok=True)

        for name in names:
            plan = plan_bundle(name, cfg, args.provider)
            if plan.skip_reason:
                print(f"SKIPPED  {name}: {plan.skip_reason}", file=sys.stderr)
                exit_code = 1
                continue
            for note in plan.notes:
                print(f"WARNING  {name}: {note}", file=sys.stderr)
            sh_path = args.out_dir / f"{name}.sh"
            write_file(sh_path, render_sh(plan), executable=True)
            print(f"wrote    {sh_path.relative_to(PROJECT_ROOT) if sh_path.is_relative_to(PROJECT_ROOT) else sh_path}")
            if not args.no_cmd:
                cmd_path = args.out_dir / f"{name}.cmd"
                write_file(cmd_path, render_cmd(plan, sh_path.as_posix(), args.distro))
                print(f"wrote    {cmd_path.relative_to(PROJECT_ROOT) if cmd_path.is_relative_to(PROJECT_ROOT) else cmd_path}")

    if args.clean:
        for path in clean_stale(set(bundles), args.out_dir):
            print(f"removed  {path}")

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
